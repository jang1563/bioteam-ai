def _build_key_findings_html(findings: list) -> str:
    if not findings:
        return ""
    items = "".join(f"<li>{_esc(str(f))}</li>" for f in findings)
    return f"<h2>Key Findings</h2><ul>{items}</ul>"


def _build_expression_html(expr: dict) -> str:
    if not expr or (not expr.get("up_regulated") and not expr.get("down_regulated")):
        return ""

    rows = ""
    for deg in (expr.get("up_regulated", []) + expr.get("down_regulated", []))[:20]:
        if isinstance(deg, dict):
            direction = "up" if deg.get("log2FC", 0) > 0 else "down"
            rows += f"<tr><td>{_esc(str(deg.get('gene', '')))}</td><td>{_esc(str(deg.get('log2FC', '')))}</td>"
            rows += f"<td>{_esc(str(deg.get('padj', '')))}</td><td>{direction}</td></tr>"

    return f"""<h2>Expression Analysis</h2>
<p>Total DEGs: {_esc(str(expr.get('total_degs', 'N/A')))} | {_esc(str(expr.get('comparison', '')))}</p>
<table><tr><th>Gene</th><th>log2FC</th><th>padj</th><th>Direction</th></tr>
{rows}
</table>"""


def _build_pathway_html(pathway: dict) -> str:
    if not pathway or not pathway.get("top_pathways"):
        return ""

    rows = ""
    for p in pathway.get("top_pathways", [])[:15]:
        if isinstance(p, dict):
            rows += f"<tr><td>{_esc(str(p.get('source', '')))}</td><td>{_esc(str(p.get('name', '')))}</td>"
            rows += f"<td>{_esc(str(p.get('pvalue', '')))}</td></tr>"

    return f"""<h2>Pathway Enrichment</h2>
<p>Significant terms: {_esc(str(pathway.get('significant_terms', 'N/A')))}</p>
<table><tr><th>Source</th><th>Term</th><th>P-value</th></tr>
{rows}
</table>"""


def _build_variant_html(variant: dict) -> str:
    if not variant or not variant.get("high_impact_variants"):
        return ""

    rows = ""
    for v in variant.get("high_impact_variants", [])[:20]:
        if isinstance(v, dict):
            rows += f"<tr><td>{_esc(str(v.get('gene', '')))}</td><td>{_esc(str(v.get('consequence', '')))}</td>"
            rows += f"<td>{_esc(str(v.get('significance', '')))}</td></tr>"

    return f"""<h2>Variant Annotation</h2>
<p>Total variants: {_esc(str(variant.get('total_variants', 'N/A')))} | High impact: {len(variant.get('high_impact_variants', []))}</p>
<table><tr><th>Gene</th><th>Consequence</th><th>Significance</th></tr>
{rows}
</table>"""


def _build_limitations_html(limitations: list) -> str:
    if not limitations:
        return ""
    items = "".join(f"<li>{_esc(str(lim))}</li>" for lim in limitations)
    return f"<h2>Limitations</h2><ul class='warning'>{items}</ul>"


def export_html(report: dict) -> str:
    """Generate a self-contained HTML report from W9 results."""
    return _HTML_TEMPLATE.safe_substitute(
        query=_esc(str(report.get("query", "N/A"))),
        workflow_id=_esc(str(report.get("workflow_id", "N/A"))),
        generated_at=_esc(str(report.get("generated_at", datetime.now(timezone.utc).isoformat()))),
        total_cost=f"{report.get('total_cost_usd', 0):.2f}",
        executive_summary=_esc(str(report.get("executive_summary", "No summary available."))),
        key_findings_html=_build_key_findings_html(report.get("key_findings", [])),
        expression_html=_build_expression_html(report.get("expression_analysis", {})),
        pathway_html=_build_pathway_html(report.get("pathway_enrichment", {})),
        variant_html=_build_variant_html(report.get("variant_annotation", {})),
        limitations_html=_build_limitations_html(report.get("limitations", [])),
    )


# ---------------------------------------------------------------------------
# JSON Export (passthrough with formatting)
# ---------------------------------------------------------------------------


def export_json(report: dict) -> str:
    """Export report as formatted JSON."""
    return json.dumps(report, indent=2, default=str, ensure_ascii=False)


# ---------------------------------------------------------------------------
# Unified export function
# ---------------------------------------------------------------------------


def export_w9_report(report: dict, output_dir: str, formats: list[str] | None = None) -> dict[str, str]:
    """Export W9 report to multiple formats.

    Args:
        report: W9BioinformaticsReport as dict.
        output_dir: Directory to write files.
        formats: List of formats to export. Default: ["tsv", "html", "json"].

    Returns:
        Dict mapping format → file path.
    """
    if formats is None:
        formats = ["tsv", "html", "json"]

    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    exported: dict[str, str] = {}

    if "tsv" in formats:
        # Write DEGs
        degs_path = out_path / "degs.tsv"
        degs_path.write_text(export_degs_tsv(report))
        exported["degs_tsv"] = str(degs_path)

        # Write variants
        variants_path = out_path / "variants.tsv"
        variants_path.write_text(export_variants_tsv(report))
        exported["variants_tsv"] = str(variants_path)

        # Write pathways
        pathways_path = out_path / "pathways.tsv"
        pathways_path.write_text(export_pathways_tsv(report))
        exported["pathways_tsv"] = str(pathways_path)

    if "html" in formats:
        html_path = out_path / "report.html"
        html_path.write_text(export_html(report))
        exported["html"] = str(html_path)

    if "json" in formats:
        json_path = out_path / "report.json"
        json_path.write_text(export_json(report))
        exported["json"] = str(json_path)

    logger.info("Exported W9 report to %s: %s", output_dir, list(exported.keys()))
    return exported
