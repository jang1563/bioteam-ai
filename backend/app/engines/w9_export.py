"""W9 result exporter — TSV, HTML, JSON formats.

Converts W9BioinformaticsReport to researcher-friendly output formats.
Uses only Python stdlib (string.Template for HTML, csv for TSV).
"""

from __future__ import annotations

import csv
import io
import json
import logging
from datetime import datetime, timezone
from html import escape as _esc
from pathlib import Path
from string import Template

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# TSV Export
# ---------------------------------------------------------------------------


def export_degs_tsv(report: dict) -> str:
    """Export DEG list as TSV (gene, log2FC, padj, direction)."""
    output = io.StringIO()
    writer = csv.writer(output, delimiter="\t")
    writer.writerow(["gene", "log2FC", "padj", "direction"])

    expr = report.get("expression_analysis", {})
    for deg in expr.get("up_regulated", []):
        if isinstance(deg, dict):
            writer.writerow([
                deg.get("gene", ""),
                deg.get("log2FC", ""),
                deg.get("padj", ""),
                "up",
            ])
    for deg in expr.get("down_regulated", []):
        if isinstance(deg, dict):
            writer.writerow([
                deg.get("gene", ""),
                deg.get("log2FC", ""),
                deg.get("padj", ""),
                "down",
            ])

    return output.getvalue()


def export_variants_tsv(report: dict) -> str:
    """Export variant annotations as TSV."""
    output = io.StringIO()
    writer = csv.writer(output, delimiter="\t")
    writer.writerow(["gene", "variant_type", "consequence", "significance"])

    variant = report.get("variant_annotation", {})
    for v in variant.get("high_impact_variants", []):
        if isinstance(v, dict):
            writer.writerow([
                v.get("gene", ""),
                v.get("type", ""),
                v.get("consequence", ""),
                v.get("significance", ""),
            ])

    return output.getvalue()


def export_pathways_tsv(report: dict) -> str:
    """Export pathway enrichment as TSV."""
    output = io.StringIO()
    writer = csv.writer(output, delimiter="\t")
    writer.writerow(["source", "term", "pvalue", "gene_ratio", "genes"])

    pathway = report.get("pathway_enrichment", {})
    for p in pathway.get("top_pathways", []):
        if isinstance(p, dict):
            genes = p.get("genes", [])
            gene_str = ",".join(genes) if isinstance(genes, list) else str(genes)
            writer.writerow([
                p.get("source", ""),
                p.get("name", ""),
                p.get("pvalue", ""),
                p.get("gene_ratio", ""),
                gene_str,
            ])

    return output.getvalue()


